"""
trustcalc.gateway.audit
=======================

Gateway audit logging.

Records authorization and execution events generated by
the ToolGateway.

Author
------
Trust Calculus Research Prototype
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any


@dataclass(slots=True)
class GatewayAudit:
    """
    Audit log for gateway operations.
    """

    _events: list[dict[str, Any]] = field(
        default_factory=list
    )

    # ---------------------------------------------------------
    # Authorization
    # ---------------------------------------------------------

    def record_authorization(
        self,
        tool_name: str,
        decision,
    ) -> None:

        self._events.append(
            {
                "timestamp": datetime.now(
                    timezone.utc
                ),
                "event": "authorization",
                "tool": tool_name,
                "allowed": decision.allowed,
                "reason": decision.explanation,
            }
        )

    # ---------------------------------------------------------
    # Execution
    # ---------------------------------------------------------

    def record_execution(
        self,
        tool_name: str,
        success: bool,
        error: str | None = None,
    ) -> None:

        self._events.append(
            {
                "timestamp": datetime.now(
                    timezone.utc
                ),
                "event": "execution",
                "tool": tool_name,
                "success": success,
                "error": error,
            }
        )

    # ---------------------------------------------------------
    # Accessors
    # ---------------------------------------------------------

    def history(self) -> list[dict[str, Any]]:
        """
        Return a copy of the audit history.
        """

        return list(self._events)

    def clear(self) -> None:
        """
        Clear the audit log.
        """

        self._events.clear()

    # ---------------------------------------------------------
    # Statistics
    # ---------------------------------------------------------

    def statistics(self) -> dict[str, int]:

        total = len(self._events)

        authorizations = sum(
            event["event"] == "authorization"
            for event in self._events
        )

        executions = sum(
            event["event"] == "execution"
            for event in self._events
        )

        allowed = sum(
            event.get("allowed", False)
            for event in self._events
            if event["event"] == "authorization"
        )

        denied = authorizations - allowed

        successful = sum(
            event.get("success", False)
            for event in self._events
            if event["event"] == "execution"
        )

        failed = executions - successful

        return {
            "events": total,
            "authorizations": authorizations,
            "executions": executions,
            "allowed": allowed,
            "denied": denied,
            "successful": successful,
            "failed": failed,
        }

    # ---------------------------------------------------------
    # Convenience
    # ---------------------------------------------------------

    def last_event(self) -> dict[str, Any] | None:

        if not self._events:
            return None

        return self._events[-1]

    def __len__(self) -> int:

        return len(self._events)

    def __iter__(self):

        return iter(self._events)